-- GO-FITNESS - Base finale propre
-- Compatible XAMPP MariaDB/MySQL
DROP DATABASE IF EXISTS `go_fitness`;
CREATE DATABASE `go_fitness` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE `go_fitness`;
SET FOREIGN_KEY_CHECKS=0;

CREATE TABLE migrations (id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, migration VARCHAR(180) NOT NULL UNIQUE, executed_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP) ENGINE=InnoDB;

CREATE TABLE users (
 iduser INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 nom VARCHAR(120) NOT NULL DEFAULT '',
 matricule VARCHAR(30) NOT NULL UNIQUE,
 username VARCHAR(60) NOT NULL UNIQUE,
 email VARCHAR(160) NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 role ENUM('admin','gerant') NOT NULL,
 is_active TINYINT(1) NOT NULL DEFAULT 1,
 failed_attempts INT NOT NULL DEFAULT 0,
 last_failed_at DATETIME NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NULL DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP,
 INDEX idx_users_role_active(role,is_active), INDEX idx_users_matricule(matricule)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE abonnes (
 idabonne BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 numero_abonne VARCHAR(20) UNIQUE,
 nom VARCHAR(80) NOT NULL,
 prenom VARCHAR(120) NOT NULL,
 tel VARCHAR(30) NOT NULL,
 adresse VARCHAR(255) NOT NULL,
 sexe ENUM('Homme','Femme','Autre') NOT NULL DEFAULT 'Homme',
 age TINYINT UNSIGNED NOT NULL,
 statut ENUM('actif','expire','suspendu','desactive') NOT NULL DEFAULT 'actif',
 created_by INT UNSIGNED NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NULL DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY (created_by) REFERENCES users(iduser) ON DELETE SET NULL,
 INDEX idx_abonnes_nom(nom,prenom), INDEX idx_abonnes_tel(tel), INDEX idx_abonnes_statut(statut)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE types_abonnement (
 idtype INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 code VARCHAR(30) NOT NULL UNIQUE,
 nom VARCHAR(50) NOT NULL UNIQUE,
 description TEXT NULL,
 is_active TINYINT(1) NOT NULL DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE modes_abonnement (
 idmode INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 code VARCHAR(30) NOT NULL UNIQUE,
 nom VARCHAR(80) NOT NULL,
 duree_jours INT UNSIGNED NOT NULL,
 allow_partial TINYINT(1) NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE tarifs (
 idtarif INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 idtype INT UNSIGNED NOT NULL,
 idmode INT UNSIGNED NOT NULL,
 montant DECIMAL(12,2) NOT NULL,
 updated_by INT UNSIGNED NULL,
 updated_at TIMESTAMP NULL DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY (idtype) REFERENCES types_abonnement(idtype),
 FOREIGN KEY (idmode) REFERENCES modes_abonnement(idmode),
 FOREIGN KEY (updated_by) REFERENCES users(iduser) ON DELETE SET NULL,
 UNIQUE KEY uq_tarif(idtype,idmode), INDEX idx_tarif_mode(idmode)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE abonnements (
 idabonnement BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 idabonne BIGINT UNSIGNED NOT NULL,
 idtype INT UNSIGNED NOT NULL,
 idmode INT UNSIGNED NOT NULL,
 date_debut DATE NOT NULL,
 date_fin DATE NOT NULL,
 jours_ajoutes INT NOT NULL DEFAULT 0,
 statut ENUM('actif','expire','suspendu','annule') NOT NULL DEFAULT 'actif',
 created_by INT UNSIGNED NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NULL DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY (idabonne) REFERENCES abonnes(idabonne),
 FOREIGN KEY (idtype) REFERENCES types_abonnement(idtype),
 FOREIGN KEY (idmode) REFERENCES modes_abonnement(idmode),
 FOREIGN KEY (created_by) REFERENCES users(iduser) ON DELETE SET NULL,
 INDEX idx_abonnements_fin(statut,date_fin), INDEX idx_abonnements_abonne(idabonne)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE paiements (
 idpaiement BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 idabonnement BIGINT UNSIGNED NULL,
 montant_total DECIMAL(12,2) NOT NULL,
 montant_paye DECIMAL(12,2) NOT NULL,
 reste_a_payer DECIMAL(12,2) NOT NULL DEFAULT 0,
 mode_paiement VARCHAR(40) NOT NULL DEFAULT 'Espèces',
 statut ENUM('paye','partiel','annule') NOT NULL DEFAULT 'paye',
 date_paiement DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 date_limite_reste DATE NULL,
 annule_motif TEXT NULL,
 annule_by INT UNSIGNED NULL,
 created_by INT UNSIGNED NULL,
 FOREIGN KEY (idabonnement) REFERENCES abonnements(idabonnement) ON DELETE SET NULL,
 FOREIGN KEY (annule_by) REFERENCES users(iduser) ON DELETE SET NULL,
 FOREIGN KEY (created_by) REFERENCES users(iduser) ON DELETE SET NULL,
 INDEX idx_paiements_date(date_paiement), INDEX idx_paiements_statut(statut)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE factures (
 idfacture BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 numero VARCHAR(20) NOT NULL UNIQUE,
 idpaiement BIGINT UNSIGNED NULL,
 type_facture ENUM('abonnement','planning') NOT NULL DEFAULT 'abonnement',
 date_facture DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 statut ENUM('valide','annulee') NOT NULL DEFAULT 'valide',
 annule_motif TEXT NULL,
 annule_by INT UNSIGNED NULL,
 created_by INT UNSIGNED NULL,
 FOREIGN KEY (idpaiement) REFERENCES paiements(idpaiement) ON DELETE SET NULL,
 FOREIGN KEY (annule_by) REFERENCES users(iduser) ON DELETE SET NULL,
 FOREIGN KEY (created_by) REFERENCES users(iduser) ON DELETE SET NULL,
 INDEX idx_factures_numero(numero), INDEX idx_factures_statut(statut)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE planning (
 idplanning BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 date_event DATE NOT NULL,
 activite VARCHAR(80) NOT NULL,
 description TEXT NULL,
 coach VARCHAR(120) NULL,
 prix_participation DECIMAL(12,2) NOT NULL DEFAULT 0,
 limite_participants INT UNSIGNED NOT NULL DEFAULT 0,
 lieu VARCHAR(180) NULL,
 date_limite_paiement DATE NOT NULL,
 statut ENUM('programme','termine','annule') NOT NULL DEFAULT 'programme',
 created_by INT UNSIGNED NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NULL DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY (created_by) REFERENCES users(iduser) ON DELETE SET NULL,
 INDEX idx_planning_date(date_event,statut)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE planning_participants (
 idparticipant BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 idplanning BIGINT UNSIGNED NOT NULL,
 idabonne BIGINT UNSIGNED NOT NULL,
 gratuit TINYINT(1) NOT NULL DEFAULT 0,
 idpaiement BIGINT UNSIGNED NULL,
 idfacture BIGINT UNSIGNED NULL,
 created_by INT UNSIGNED NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (idplanning) REFERENCES planning(idplanning),
 FOREIGN KEY (idabonne) REFERENCES abonnes(idabonne),
 FOREIGN KEY (idpaiement) REFERENCES paiements(idpaiement) ON DELETE SET NULL,
 FOREIGN KEY (idfacture) REFERENCES factures(idfacture) ON DELETE SET NULL,
 FOREIGN KEY (created_by) REFERENCES users(iduser) ON DELETE SET NULL,
 UNIQUE KEY uq_participant(idplanning,idabonne)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE notifications (
 idnotification BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 role_cible ENUM('admin','gerant','all') NOT NULL DEFAULT 'all',
 user_id INT UNSIGNED NULL,
 titre VARCHAR(160) NOT NULL,
 message TEXT NOT NULL,
 is_read TINYINT(1) NOT NULL DEFAULT 0,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (user_id) REFERENCES users(iduser) ON DELETE CASCADE,
 INDEX idx_notif(role_cible,is_read,created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE audit_logs (
 idlog BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 user_id INT UNSIGNED NULL,
 role VARCHAR(20) NULL,
 action VARCHAR(120) NOT NULL,
 entity VARCHAR(80) NULL,
 entity_id VARCHAR(40) NULL,
 old_value TEXT NULL,
 new_value TEXT NULL,
 motif TEXT NULL,
 ip_address VARCHAR(45) NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (user_id) REFERENCES users(iduser) ON DELETE SET NULL,
 INDEX idx_audit_action(action), INDEX idx_audit_date(created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

